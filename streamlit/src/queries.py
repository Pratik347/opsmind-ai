PENDING_RECOMMENDATIONS = """
SELECT
    RECOMMENDATION_ID,
    MACHINE_ID,
    ACTION_TYPE,
    PRIORITY,
    DESCRIPTION,
    RATIONALE,
    EVIDENCE_SUMMARY,
    ESTIMATED_COST_USD,
    ESTIMATED_DOWNTIME_HRS,
    RISK_IF_DEFERRED,
    GENERATED_AT
FROM OPSMIND.AI.RECOMMENDATIONS
WHERE STATUS = 'pending'
ORDER BY
    CASE PRIORITY
        WHEN 'critical' THEN 1
        WHEN 'high' THEN 2
        WHEN 'medium' THEN 3
        WHEN 'low' THEN 4
    END,
    GENERATED_AT DESC
"""

