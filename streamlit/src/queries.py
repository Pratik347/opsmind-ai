# -- Operations Overview ---------------------------------------------------

FLEET_RISK_SUMMARY = """
SELECT
    RISK_BAND,
    COUNT(*) AS MACHINE_COUNT
FROM OPSMIND.AI.FAILURE_RISK_SCORES
GROUP BY RISK_BAND
ORDER BY CASE RISK_BAND
    WHEN 'CRITICAL' THEN 1
    WHEN 'HIGH' THEN 2
    WHEN 'MEDIUM' THEN 3
    WHEN 'LOW' THEN 4
    WHEN 'INCOMPLETE' THEN 5
END
"""

OEE_FLEET_LATEST = """
SELECT
    M.MACHINE_ID,
    M.MACHINE_NAME,
    M.MACHINE_TYPE,
    PL.LINE_NAME,
    O.METRIC_DATE,
    O.OEE_PCT,
    O.AVAILABILITY_PCT,
    O.PERFORMANCE_PCT,
    O.QUALITY_PCT
FROM OPSMIND.CORE.OEE_METRICS O
JOIN OPSMIND.CORE.MACHINES M ON O.MACHINE_ID = M.MACHINE_ID
JOIN OPSMIND.CORE.PRODUCTION_LINES PL ON M.LINE_ID = PL.LINE_ID
WHERE O.METRIC_DATE = (SELECT MAX(METRIC_DATE) FROM OPSMIND.CORE.OEE_METRICS)
ORDER BY O.OEE_PCT ASC
"""

ANOMALY_RECENT = """
SELECT
    A.ANOMALY_ID,
    A.MACHINE_ID,
    M.MACHINE_NAME,
    A.SIGNAL_TYPE,
    A.SEVERITY,
    A.DEVIATION_PCT,
    A.CONFIDENCE_SCORE,
    A.DETECTED_AT,
    A.DESCRIPTION
FROM OPSMIND.CORE.ANOMALY_SIGNALS A
JOIN OPSMIND.CORE.MACHINES M ON A.MACHINE_ID = M.MACHINE_ID
ORDER BY A.DETECTED_AT DESC
LIMIT 20
"""

PLANT_SUMMARY = """
SELECT
    P.PLANT_NAME,
    P.REGION,
    COUNT(DISTINCT PL.LINE_ID) AS LINE_COUNT,
    COUNT(DISTINCT M.MACHINE_ID) AS MACHINE_COUNT
FROM OPSMIND.CORE.PLANTS P
JOIN OPSMIND.CORE.PRODUCTION_LINES PL ON P.PLANT_ID = PL.PLANT_ID
JOIN OPSMIND.CORE.MACHINES M ON PL.LINE_ID = M.LINE_ID
GROUP BY P.PLANT_NAME, P.REGION
"""

